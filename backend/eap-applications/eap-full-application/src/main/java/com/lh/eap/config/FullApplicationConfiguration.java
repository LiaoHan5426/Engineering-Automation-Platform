public class FullApplicationConfiguration {
    /** Legacy manifests use SQL v1; explicit bindings must match an installed behavior version. */
    @org.springframework.context.annotation.Bean
    @org.springframework.boot.autoconfigure.condition.ConditionalOnMissingBean(com.lh.eap.core.ExpertAnalysisPolicyResolver.class)
    com.lh.eap.core.ExpertAnalysisPolicyResolver expertAnalysisPolicyResolver(
            com.lh.eap.application.service.SqlExpertAnalysisPolicy sqlPolicy) {
        var binding = new com.lh.eap.domain.model.ExpertBehaviorBinding("sql-analysis", 1);
        return new com.lh.eap.core.ExpertBehaviorCatalog(java.util.List.of(
                new com.lh.eap.core.ExpertBehaviorCatalog.Registration(binding, "SQL 专业分析", sqlPolicy),
                new com.lh.eap.core.ExpertBehaviorCatalog.Registration(com.lh.eap.ai.SqlExpertAgentService.BINDING,
                        "SQL 只读取证 Agent", sqlPolicy, "agent", com.lh.eap.ai.SqlExpertAgentService.TOOLS, java.util.Set.of("sql.parse"))), binding);
    }

    @org.springframework.context.annotation.Bean
    com.lh.eap.runtime.handler.CapabilityHandlerRegistry capabilityHandlerRegistry(
            java.util.List<com.lh.eap.runtime.handler.CapabilityHandler> handlers,
            com.lh.eap.application.service.CapabilitySettings settings) {
        return new com.lh.eap.runtime.handler.CapabilityHandlerRegistry(handlers, settings);
    }

}
