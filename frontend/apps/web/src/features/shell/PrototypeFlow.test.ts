// @vitest-environment happy-dom
import { afterEach, expect, it, vi } from 'vite-plus/test';
import { createApp, h, nextTick, type App } from 'vue';
import { runtimeApi } from '@eap/runtime-client';
import { i18n } from '../../lib/i18n';
import PrototypeFlow from './PrototypeFlow.vue';
import { preview } from './preview';
import { workbench } from './workbench';
let app: App; let root: HTMLDivElement;
afterEach(() => { app?.unmount(); root?.remove(); localStorage.clear(); workbench.drafts = []; vi.restoreAllMocks(); });
it('saves a design and prepares an isolated mock conversation without sending or writing', async () => {
  const send = vi.spyOn(runtimeApi, 'sendAiMessage');
  const apply = vi.spyOn(runtimeApi, 'applyCodeProposal');
  const navigate = vi.fn(); workbench.preview = true;
  root = document.createElement('div'); document.body.append(root);
  app = createApp({ render: () => h(PrototypeFlow, { onNavigate: navigate }) }); app.use(i18n).mount(root); await nextTick();
  const prepare = root.querySelector('[data-testid="prepare-prototype"]') as HTMLButtonElement;
  expect(prepare.disabled).toBe(true);
  expect(root.textContent).toContain('frontend/apps/web/src/features/chat/TaskComposer.vue');
  expect(root.textContent).toContain('无退出码');
  expect(root.textContent).not.toContain('demo passed');
  expect(root.textContent).toContain('实现执行器：未接通');
  expect(root.textContent).toContain('模型：未调用');
  expect(root.textContent).toContain('typecheck、test、build 均未请求');
  (root.querySelector('[data-testid="draft-nav"]') as HTMLButtonElement).click();
  (root.querySelector('[data-testid="draft-plus"]') as HTMLButtonElement).click();
  (root.querySelector('[data-testid="draft-summary"]') as HTMLButtonElement).click();
  (root.querySelector('[data-testid="draft-save"]') as HTMLButtonElement).click(); await nextTick();
  expect(workbench.drafts[0]?.acceptance).toEqual(['nav', 'popover', 'panel']);
  expect(prepare.disabled).toBe(true);
  expect(root.textContent).toContain('Java 进程机器路径未知');
  expect(root.textContent).toContain('页面预览：模拟模式不提供真实预览地址');
  expect(root.textContent).toContain('交互验收：未完成');
  expect(root.textContent).toContain('基线哈希：未知');
  (root.querySelector('[data-testid="confirm-scope"]') as HTMLInputElement).click(); await nextTick();
  expect(prepare.disabled).toBe(true);
  (root.querySelector('[data-testid="confirm-design"]') as HTMLInputElement).click(); await nextTick();
  expect(prepare.disabled).toBe(false);
  prepare.click(); await nextTick();
  const session = preview.current('code');
  expect(session.context.prototypeVersionId).toBe(workbench.drafts[0].id);
  expect(session.context.instructions).toContain('frontend/apps/web/src/features/chat/TaskComposer.vue');
  expect(session.context.instructions).toContain('不生成脱离项目的新壳');
  expect(session.context.instructions).not.toContain('demo passed');
  expect(workbench.sessionExtras[session.id]?.delivery).toEqual({ versionId: workbench.drafts[0].id, pagePath: 'frontend/apps/web/src/features/chat/TaskComposer.vue', pageLabel: 'preview.pageComposer' });
  expect(session.turns).toEqual([]); expect(session.draft).not.toBe('');
  expect(navigate).toHaveBeenCalledWith('chat'); expect(send).not.toHaveBeenCalled(); expect(apply).not.toHaveBeenCalled();
});
