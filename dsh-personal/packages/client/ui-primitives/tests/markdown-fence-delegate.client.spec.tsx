import { nextTick } from 'vue'
import { h } from 'vue'
// @vitest-environment jsdom
import { afterEach, describe, expect, it, vi } from 'vitest'
import { cleanup, render, screen } from './content-render.ts'
import type { VNodeChild } from 'vue'
import { MarkdownText } from '../src/markdown/MarkdownText.tsx'
import { MarkdownDelegateProvider } from '../src/markdown/MarkdownDelegate.tsx'
import { FenceCodeBlock } from '../src/markdown/FenceBlocks.tsx'
import type { MarkdownDelegateFenceInfo } from '../src/markdown/MarkdownDelegate.tsx'
import { markdownLabels } from './labels.client.ts'
afterEach(cleanup)
const FENCE_TS = ['```TS', 'const a = 1', '```'].join('\n')
const FENCE_PLAIN = ['```', 'plain', '```'].join('\n')
const FENCE_EMPTY_TS = ['```ts', '```'].join('\n')
const FENCE_MATH = ['```math', 'x', '```'].join('\n')
const FENCE_DIFF = ['```diff', '-a', '+b', '```'].join('\n')
function renderFenceSpy() {
  return vi.fn((fence: MarkdownDelegateFenceInfo): VNodeChild => h('output', { 'data-testid': 'fence' }, [fence.lang, ':', fence.code]))
}
describe('MarkdownDelegate.renderCode', () => {
  it('passes a final-language fence to the delegate with its lowercased language', async () => {
    const renderCode = renderFenceSpy()
    const { container } = render(h(MarkdownDelegateProvider, { 'renderCode': renderCode }, { 'default': () => [h(MarkdownText, { 'text': FENCE_TS, 'labels': markdownLabels })] }))
    await nextTick()
    await nextTick()
    expect(renderCode).toHaveBeenCalledWith({ lang: 'ts', code: 'const a = 1', streaming: false })
    await nextTick()
    expect(renderCode.mock.calls[0]?.[0].meta).toBeUndefined()
    await nextTick()
    expect(screen.getByTestId('fence').textContent).toBe('ts:const a = 1')
    await nextTick()
    expect(container.querySelector('.md-code-block')).toBeNull()
  })
  it('passes the rest of the info string as meta', async () => {
    const renderCode = renderFenceSpy()
    render(h(MarkdownDelegateProvider, { 'renderCode': renderCode }, { 'default': () => [h(MarkdownText, { 'text': '```HTML width=480 height=360\n<p>x</p>\n```', 'labels': markdownLabels })] }))
    await nextTick()
    await nextTick()
    expect(renderCode).toHaveBeenCalledWith({ lang: 'html', code: '<p>x</p>', streaming: false, meta: 'width=480 height=360' })
    await nextTick()
    expect(renderCode.mock.calls[0]?.[0]).toHaveProperty('meta', 'width=480 height=360')
  })
  it('keeps language-less and empty fences on the built-in blocks', async () => {
    const renderCode = renderFenceSpy()
    const { container } = render(h(MarkdownDelegateProvider, { 'renderCode': renderCode }, { 'default': () => [h(MarkdownText, { 'text': `${FENCE_PLAIN}\n\n${FENCE_EMPTY_TS}`, 'labels': markdownLabels })] }))
    await nextTick()
    await nextTick()
    expect(renderCode).not.toHaveBeenCalled()
    await nextTick()
    expect(container.querySelector('.md-code-block pre')?.textContent).toBe('plain')
    const empty = container.querySelector('pre > code.language-ts')
    await nextTick()
    expect(empty).not.toBeNull()
    await nextTick()
    expect(empty!.outerHTML).toBe('<code class="language-ts"></code>')
  })
  it('hands math and diff fences to the delegate too', async () => {
    const renderCode = renderFenceSpy()
    const { container } = render(h(MarkdownDelegateProvider, { 'renderCode': renderCode }, { 'default': () => [h(MarkdownText, { 'text': `${FENCE_MATH}\n\n${FENCE_DIFF}`, 'labels': markdownLabels })] }))
    await nextTick()
    await nextTick()
    expect(renderCode).toHaveBeenCalledTimes(2)
    await nextTick()
    expect(renderCode.mock.calls.map(([fence]) => fence.lang)).toEqual(['math', 'diff'])
    await nextTick()
    expect(container.querySelector('.katex')).toBeNull()
  })
  it('waits for the info string to finish while streaming', async () => {
    const renderCode = renderFenceSpy()
    const { rerender } = render(h(MarkdownDelegateProvider, { 'renderCode': renderCode }, { 'default': () => [h(MarkdownText, { 'text': '```t', 'streaming': true, 'labels': markdownLabels })] }))
    await nextTick()
    await nextTick()
    expect(renderCode).not.toHaveBeenCalled()
    rerender(h(MarkdownDelegateProvider, { 'renderCode': renderCode }, { 'default': () => [h(MarkdownText, { 'text': '```ts\nlet a', 'streaming': true, 'labels': markdownLabels })] }))
    await nextTick()
    expect(renderCode).toHaveBeenCalledTimes(1)
    await nextTick()
    expect(renderCode).toHaveBeenCalledWith({ lang: 'ts', code: 'let a', streaming: true })
  })
  it('a provider change reaches a frozen streaming fence', async () => {
    const text = ['```ts', 'const a = 1', '```', '', 'alpha', '', 'beta', '', 'gamma'].join('\n')
    const first = (): VNodeChild => h('i', null, ['first'])
    const second = (): VNodeChild => h('i', null, ['second'])
    const { rerender } = render(h(MarkdownDelegateProvider, { 'renderCode': first }, { 'default': () => [h(MarkdownText, { 'text': text, 'streaming': true, 'labels': markdownLabels })] }))
    await nextTick()
    await nextTick()
    expect(screen.getByText('first')).toBeTruthy()
    rerender(h(MarkdownDelegateProvider, { 'renderCode': second }, { 'default': () => [h(MarkdownText, { 'text': text, 'streaming': true, 'labels': markdownLabels })] }))
    await nextTick()
    expect(screen.getByText('second')).toBeTruthy()
    await nextTick()
    expect(screen.queryByText('first')).toBeNull()
  })
  it('places the delegate output in a fence seat directly under the document root', async () => {
    const renderCode = renderFenceSpy()
    const { container } = render(h(MarkdownDelegateProvider, { 'renderCode': renderCode }, { 'default': () => [h(MarkdownText, { 'text': `before\n\n${FENCE_TS}\n\nafter`, 'labels': markdownLabels })] }))
    await nextTick()
    const seat = screen.getByTestId('fence').parentElement
    await nextTick()
    expect(seat?.className).toContain('_fenceSeat_')
    await nextTick()
    expect(seat?.parentElement).toBe(container.firstElementChild)
    await nextTick()
    expect(seat?.children).toHaveLength(1)
  })
  it('renders fences without a seat when no delegate is present', async () => {
    const { container } = render(h(MarkdownText, { 'text': `${FENCE_TS}\n\n${FENCE_MATH}`, 'labels': markdownLabels }))
    await nextTick()
    await nextTick()
    expect(container.querySelector('.md-code-block')).not.toBeNull()
    await nextTick()
    expect(container.querySelector('[class*="_fenceSeat_"]')).toBeNull()
  })
  it('keeps one delegated code block instance while the fence streams and settles', async () => {
    const renderCode = vi.fn((fence: MarkdownDelegateFenceInfo): VNodeChild => (h(FenceCodeBlock, { 'lang': fence.lang, 'code': fence.code, 'streaming': fence.streaming, 'labels': markdownLabels.code })))
    const view = (text: string, streaming: boolean) => (h(MarkdownDelegateProvider, { 'renderCode': renderCode }, { 'default': () => [h(MarkdownText, { 'text': text, 'streaming': streaming, 'labels': markdownLabels })] }))
    const { container, rerender } = render(view('```ts\nconst a = 1\n', true))
    await nextTick()
    const block = container.querySelector('.md-code-block')
    const seat = container.querySelector('[class*="_fenceSeat_"]')
    await nextTick()
    expect(block).not.toBeNull()
    await nextTick()
    expect(seat?.firstElementChild).toBe(block)
    rerender(view('```ts\nconst a = 1\nconst b = 2\n', true))
    await nextTick()
    expect(container.querySelector('.md-code-block')).toBe(block)
    await nextTick()
    expect(container.querySelector('[class*="_fenceSeat_"]')).toBe(seat)
    rerender(view('```ts\nconst a = 1\nconst b = 2\n```', false))
    await nextTick()
    expect(container.querySelector('.md-code-block')).toBe(block)
    await nextTick()
    expect(container.querySelector('[class*="_fenceSeat_"]')).toBe(seat)
    await nextTick()
    expect(renderCode.mock.calls.map(([fence]) => fence.streaming)).toEqual([true, true, false])
    await nextTick()
    expect(block?.querySelector('pre')?.textContent).toBe('const a = 1\nconst b = 2')
  })
  it('passes the info string meta while streaming', async () => {
    const renderCode = renderFenceSpy()
    render(h(MarkdownDelegateProvider, { 'renderCode': renderCode }, { 'default': () => [h(MarkdownText, { 'text': '```ts title=x\nlet a', 'streaming': true, 'labels': markdownLabels })] }))
    await nextTick()
    await nextTick()
    expect(renderCode).toHaveBeenCalledWith({ lang: 'ts', code: 'let a', streaming: true, meta: 'title=x' })
  })
  it('renders the built-in blocks without a delegate', async () => {
    const math = render(h(MarkdownText, { 'text': FENCE_MATH, 'labels': markdownLabels }))
    await nextTick()
    await nextTick()
    expect(math.container.querySelector('.katex')).not.toBeNull()
    math.unmount()
    const diff = render(h(MarkdownText, { 'text': FENCE_DIFF, 'labels': markdownLabels }))
    await nextTick()
    await nextTick()
    expect(diff.container.querySelector('pre')!.textContent).toBe('-a\n+b')
  })
})
